def law_topics(title):
    if title.startswith("Закон за ратифициране"):
        return []
    return [k for k, r in _LAW if r.search(title)]


def entity_topics(name):
    u = name.upper()
    return [k for k, r in _ENT if r.search(u)]


def short_title(t):
    """'Общ законопроект на приетите на … законопроект за изменение на Семейния кодекс, № …' -> 'Закон за изменение на Семейния кодекс'."""
    if not re.match(r"\s*Общ\s+(?:законо)?проект", t, re.I):
        return t
    head = re.split(r",?\s*№|,\s*изготвен|,\s*внесен|;|,?\s+\d{2}-\d{3}-|\s+вносител", t, maxsplit=1)[0]
    parts = re.split(r"(?:[Зз]аконо)?[Пп]роект(?:и|г)?\s+|ЗИД\s+", head)
    tail = next((p for p in reversed(parts) if p.strip() and "приетите" not in p), "").strip(" ,.")
    if not tail:
        return t
    if tail.startswith("на "):
        tail = "за изменение и допълнение " + tail
    return "Закон " + tail
